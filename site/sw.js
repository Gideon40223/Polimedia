// Polimedia – Service Worker
// Macht die Seite als App installierbar und zeigt ohne Internet den zuletzt geladenen Feed.
// Regel: immer zuerst das Netz fragen (damit der Feed aktuell ist), nur offline aus dem Zwischenspeicher.

const CACHE = "polimedia-v1";

self.addEventListener("install", () => self.skipWaiting());
self.addEventListener("activate", (e) => e.waitUntil(self.clients.claim()));

self.addEventListener("fetch", (e) => {
  const url = new URL(e.request.url);
  if (e.request.method !== "GET" || url.origin !== self.location.origin) return;
  e.respondWith(
    fetch(e.request)
      .then((antwort) => {
        const kopie = antwort.clone();
        caches.open(CACHE).then((c) => c.put(e.request, kopie));
        return antwort;
      })
      .catch(() => caches.match(e.request, { ignoreSearch: true }))
  );
});
